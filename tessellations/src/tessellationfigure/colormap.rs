//! Affine maps from each hand-made figure to the coordinate system of its
//! tactile-rs tiling type, used to read the `(aspect, t1, t2)` label of a tile
//! from its centroid. Generated from the tactile-rs default tiling data.

use crate::tessellationfigure::coloring::ColorTable;
use crate::tessellationline::Point;

/// Number of tile aspects (poses) a colouring can distinguish.
pub const MAX_ASPECTS: usize = 12;

/// An affine map from the figure plane to the tactile-rs plane.
#[derive(Clone, Copy, Debug)]
pub struct ColorMap {
    /// Isohedral tiling type number (1-93).
    pub ih: u8,
    /// Number of aspects in the colour table.
    pub aspects: usize,
    /// Linear part of the map, row-major: `[m11, m21, m12, m22]`.
    pub linear: [f32; 4],
    /// Centroid of the base tile in tactile coordinates.
    pub c0t: [f32; 2],
    /// Centroid of each aspect transform applied to the base centroid.
    pub aspect_centroids: [[f32; 2]; MAX_ASPECTS],
    /// Tactile lattice basis.
    pub t1: [f32; 2],
    pub t2: [f32; 2],
}

/// Colour of `p`, or `None` if its centroid is not close enough to a
/// lattice point of any aspect (for example after the tile was edited).
impl ColorMap {
    pub fn color(
        &self,
        p: &crate::tessellationfigure::Placement,
        table: &ColorTable,
        base: Point,
    ) -> Option<usize> {
        let [m11, m21, m12, m22] = self.linear;
        let dx = self.c0t[0] - (m11 * base.x + m21 * base.y);
        let dy = self.c0t[1] - (m12 * base.x + m22 * base.y);
        let c = p.transform.transform_point(base);
        let qx = m11 * c.x + m21 * c.y + dx;
        let qy = m12 * c.x + m22 * c.y + dy;
        let det = self.t1[0] * self.t2[1] - self.t1[1] * self.t2[0];
        let mut best: Option<(f32, usize, i64, i64)> = None;
        for a in 0..self.aspects {
            let ax = qx - self.aspect_centroids[a][0];
            let ay = qy - self.aspect_centroids[a][1];
            let u = (ax * self.t2[1] - ay * self.t2[0]) / det;
            let v = (self.t1[0] * ay - self.t1[1] * ax) / det;
            let (ru, rv) = (u.round(), v.round());
            let err = (u - ru).abs().max((v - rv).abs());
            if best.is_none_or(|(e, _, _, _)| err < e) {
                best = Some((err, a, ru as i64, rv as i64));
            }
        }
        let (err, aspect, t1, t2) = best?;
        if err < 0.05 {
            Some(table.color(aspect, t1, t2))
        } else {
            None
        }
    }
}

/// Colour map for an isohedral tiling type.
pub fn color_map(ih: u8) -> Option<&'static ColorMap> {
    COLOR_MAPS.iter().find(|m| m.ih == ih)
}

